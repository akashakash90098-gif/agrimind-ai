/**
 * Get current stored language or default to 'en'
 */
function getCurrentLanguage() {
  const saved = localStorage.getItem('agrimind_lang');
  if (saved && ['en', 'te', 'ta', 'hi'].includes(saved)) {
    return saved;
  }
  return 'en';
}

/**
 * Apply translations to the DOM
 */
function applyLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  localStorage.setItem('agrimind_lang', lang);
  document.documentElement.lang = lang;

  // Translate elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    } else if (translations['en'] && translations['en'][key]) {
      el.textContent = translations['en'][key];
    }
  });

  // Translate placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[lang] && translations[lang][key]) {
      el.setAttribute('placeholder', translations[lang][key]);
    } else if (translations['en'] && translations['en'][key]) {
      el.setAttribute('placeholder', translations['en'][key]);
    }
  });

  // Update language selector button label if present
  const currentLangLabel = document.getElementById('currentLangLabel');
  if (currentLangLabel) {
    const labels = {
      en: 'English',
      te: 'తెలుగు (Telugu)',
      ta: 'தமிழ் (Tamil)',
      hi: 'हिन्दी (Hindi)'
    };
    currentLangLabel.textContent = labels[lang] || 'English';
  }

  // Highlight active option in dropdown
  document.querySelectorAll('.lang-option').forEach(opt => {
    const optLang = opt.getAttribute('data-lang');
    if (optLang === lang) {
      opt.classList.add('active');
    } else {
      opt.classList.remove('active');
    }
  });
}

// Export for window
window.agrimindI18n = {
  getLanguage: getCurrentLanguage,
  setLanguage: applyLanguage,
  translations: translations
};

// Auto initialize on DOM ready
document.addEventListener('DOMContentLoaded', () => {
  const lang = getCurrentLanguage();
  applyLanguage(lang);
});
